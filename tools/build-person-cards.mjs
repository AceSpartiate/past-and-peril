/* build-person-cards.mjs — bake the student-safe half of the deck into the app.
 *
 *     node tools\build-person-cards.mjs
 *
 * Run automatically by tools/make-release.mjs. Writes
 * app/content/person-cards.json.
 *
 * ---------------------------------------------------------------------------
 * WHY THIS EXISTS
 *
 * The research deck lives in player-materials/, which is deliberately NOT in
 * the repository and NOT in the release: it holds each character's own secret,
 * and publishing it would let every student read every other student's.
 *
 * But the person cards are the opposite — the biography of a real person is
 * exactly what a student should read. So server/people.js was reading a folder
 * that does not exist anywhere except this machine, and on any other install it
 * silently served zero cards. Nothing errored. The panel just never appeared.
 *
 * So the SAFE half is baked out to JSON and shipped, and the markdown stays
 * private and stays the source. What gets written here is precisely what a
 * student would have seen anyway: server/people.js has already stripped the
 * teacher-only sections and dropped the metadata header that contradicts the
 * roster. This is a build artifact, never hand-edited — regenerate it rather
 * than fixing it.
 */

import fs from 'fs';
import path from 'path';
import { createRequire } from 'module';
import { fileURLToPath } from 'url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(HERE, '..');
const require = createRequire(import.meta.url);

const OUT = path.join(ROOT, 'app', 'content', 'person-cards.json');
const say = (s) => console.log(s === undefined ? '' : '  ' + s);

/* Read the deck through people.js so the stripping rules are the same ones the
 * server uses — a second implementation here would be a second thing to get
 * wrong, and the thing it would get wrong is what children can read. */
const people = require(path.join(ROOT, 'server', 'people.js'));

const deckPresent = fs.existsSync(
  path.join(ROOT, 'player-materials', 'person-cards-gonzales.md'));

if (!deckPresent) {
  say('');
  say('No player-materials/ here, so there is nothing to build from.');
  say('That is normal on an installed copy: app/content/person-cards.json');
  say('is already there and is what the server reads.');
  say('');
  process.exit(0);
}

const roster = JSON.parse(fs.readFileSync(
  path.join(ROOT, 'app', 'content', 'roster-s1.json'), 'utf8')).roster;

const out = { _note: 'GENERATED by tools/build-person-cards.mjs — do not edit.', cards: {} };
const missing = [];
roster.forEach((p) => {
  const card = people.forName(p.name);
  if (!card) { missing.push(p.name); return; }
  /* keyed by roster id, so the client never sees the name-matching heuristic */
  out.cards[p.id] = { name: card.name, blocks: card.blocks };
});

fs.writeFileSync(OUT, JSON.stringify(out, null, 1) + '\n', 'utf8');

/* A last guard at the point of publication. server/people.js strips the
 * teacher-only sections and tools/check-people.mjs proves it, but this file is
 * the thing that actually ships, so check the bytes that are going out. */
const written = fs.readFileSync(OUT, 'utf8').toLowerCase();
const forbidden = ['deck balancing', 'do not put these on cards',
                   'for the teacher only', 'yours to play'];
const leaked = forbidden.filter((s) => written.indexOf(s) !== -1);

say('');
say(Object.keys(out.cards).length + ' of ' + roster.length + ' characters have a card');
if (missing.length) say('no card: ' + missing.join(', '));
say(Math.round(fs.statSync(OUT).size / 1024) + ' KB written to app/content/person-cards.json');
if (leaked.length) {
  say('');
  say('REFUSING TO SHIP: teacher-only text found in the output — ' + leaked.join(', '));
  fs.unlinkSync(OUT);
  process.exit(1);
}
say('nothing teacher-only in it');
say('');
